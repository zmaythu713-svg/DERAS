    public static function forCategory(string $categorySlug): array
    {
        return match ($categorySlug) {
            Category::TEXTBOOK => self::textbookMap(),
            Category::TEACHER_HANDBOOK => self::teacherHandbookMap(),
            Category::TEACHER_GUIDE => self::teacherGuideMap(),
            default => [],
        };
    }

    /**
     * Subject names for one grade + category (empty if unknown).
     */
    public static function subjectsFor(string $gradeName, string $categorySlug): array
    {
        $map = self::forCategory($categorySlug);

        return $map[$gradeName] ?? [];
    }

